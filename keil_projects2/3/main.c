// ???? ??????? delay — ???????? count ??????????? ???????????
void delay() {
    volatile uint32_t count = 355;  // ????????? ????????, ?????????!
    while(count--) __NOP();
}

int main() {
    // ===== PA4 ????? ?????? ?????? ? ????????? =====
    // ?????? ????????? (?? RM0008)
    uint32_t* RCC_APB2ENR  = (uint32_t*)(0x40021018);
    uint32_t* GPIOA_CRL    = (uint32_t*)(0x40010800);
    uint32_t* GPIOA_BSRR   = (uint32_t*)(0x40010810);
    uint32_t* GPIOA_BRR    = (uint32_t*)(0x40010814);

    // ???????? ???????????? GPIOA (??? 2)
    *RCC_APB2ENR |= (1 << 2);

    // PA4 ??? ????? 2MHz push-pull: CNF=00, MODE=10
    *GPIOA_CRL &= ~(0xF << 16);   // ???????? ???? 19:16
    *GPIOA_CRL |=  (0x2 << 16);   // MODE4 = 10 (2MHz output)

    // ??????? ????? ??? PA4
    uint32_t PA4_BIT = (1 << 4);

    // ===== PA10 ????? CMSIS =====
    RCC->APB2ENR |= RCC_APB2ENR_IOPAEN;
    GPIOA->CRH &= ~(GPIO_CRH_MODE10 | GPIO_CRH_CNF10);
    SET_BIT(GPIOA->CRH, GPIO_CRH_MODE10_1);  // MODE10 = 10 (2MHz)

    // ===== ??????? ???? =====
    // PA4: 3720 ??, PA10: 7440 ?? (? 2 ???? ????)
    // ?? ???? ?????? ?????: PA4 ?????? 1 ??????, PA10 ?????? 2 ???????
    for(;;) {
        // PA4=1, PA10=1
        *GPIOA_BSRR = PA4_BIT;
        GPIOA->BSRR = GPIO_BSRR_BS10;
        delay();

        // PA4=1, PA10=0  ? PA10 ????????????
        *GPIOA_BSRR = PA4_BIT;
        GPIOA->BRR = GPIO_BRR_BR10;
        delay();

        // PA4=0, PA10=1  ? PA4 ? PA10 ?????????????
        *GPIOA_BRR = PA4_BIT;
        GPIOA->BSRR = GPIO_BSRR_BS10;
        delay();

        // PA4=0, PA10=0  ? PA10 ????????????
        *GPIOA_BRR = PA4_BIT;
        GPIOA->BRR = GPIO_BRR_BR10;
        delay();
    }
}